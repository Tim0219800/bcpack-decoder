#[cfg(test)]
mod tests {
    use super::FREQ;
    use crate::model::models;

    #[test]
    fn generated_tables_match_the_microsoft_sample() {
        let m = models().unwrap();
        for w in 1..=8u32 {
            for q in 0..16u32 {
                let t = m.get(q, w);
                let bands = FREQ[w as usize - 1][q as usize];
                for v in 0..(1usize << w) {
                    let k = (usize::BITS - v.leading_zeros()) as usize;
                    let start = if k == 0 { 0 } else { 1usize << (k - 1) };
                    let base: u32 = (0..k)
                        .map(|j| bands[j] * if j == 0 { 1 } else { 1 << (j - 1) })
                        .sum();
                    let cum = (base + bands[k] * (v - start) as u32).max(1);
                    assert_eq!(t.cum[v], cum, "q={q} w={w} symbol {v}");
                }
                assert_eq!(t.cum[1 << w], 65536, "q={q} w={w}");
            }
        }
    }
}
